func TestExportArchiveLeavesOutKeyArmorAnywhereInTheFirstWindow(t *testing.T) {
	t.Parallel()
	armors := map[string]string{
		"rsa":        pemRSA,
		"ec":         keyArmor("EC PRIVATE KEY"),
		"openssh":    keyArmor("OPENSSH PRIVATE KEY"),
		"encrypted":  keyArmor("ENCRYPTED PRIVATE KEY"),
		"pkcs8":      keyArmor("PRIVATE KEY"),
		"pgp":        keyArmor("PGP PRIVATE KEY BLOCK"),
		"after text": "# generated by a tool\nsome: setting\n" + pemRSA,
		"boundary":   strings.Repeat("#", 64<<10-strings.Index(pemRSA, "\n")) + pemRSA,
	}
	files := map[string]string{}
	for name, content := range armors {
		files["config/ssl/"+strings.ReplaceAll(name, " ", "_")+".txt"] = content
	}
	files["config/ssl/kept.txt"] = "plain text\n"
	entries := exportedKeyTree(t, files)

	for name := range armors {
		require.NotContains(t, entries, "config/ssl/"+strings.ReplaceAll(name, " ", "_")+".txt", name)
	}
	require.Contains(t, entries, "config/ssl/kept.txt")
}

