func TestExportArchiveLeavesOutKeyFilesByName(t *testing.T) {
	t.Parallel()
	entries := exportedKeyTree(t, map[string]string{
		"config/ssl/client.key":       "opaque 1\n",
		"config/ssl/CLIENT2.KEY":      "opaque 2\n",
		"config/ssl/bundle.p12":       "opaque 3\n",
		"config/ssl/bundle.pfx":       "opaque 4\n",
		"config/ssl/keyring.txt":      "kept\n",
		"config/ssl/client.key.notes": "kept too\n",
		"config/ssl/monkey":           "kept as well\n",
	})

	for _, name := range []string{"client.key", "CLIENT2.KEY", "bundle.p12", "bundle.pfx"} {
		require.NotContains(t, entries, "config/ssl/"+name, name)
	}
	for _, name := range []string{"keyring.txt", "client.key.notes", "monkey"} {
		require.Contains(t, entries, "config/ssl/"+name, name)
	}
}

func TestExportArchiveLeavesOutYAMLWithAnInlineKey(t *testing.T) {
	t.Parallel()
	inline := "tls:\n  cert: |\n" + indent(pemCert) + "  key: |\n" + indent(pemRSA)
	entries := exportedKeyTree(t, map[string]string{
		"config/extra/tls.yaml":   inline,
		"config/extra/plain.yaml": "tls:\n  cert: |\n" + indent(pemCert),
	})

	require.NotContains(t, entries, "config/extra/tls.yaml")
	require.Contains(t, entries, "config/extra/plain.yaml")
}

func indent(block string) string {
	var out strings.Builder
	for _, line := range strings.Split(strings.TrimRight(block, "\n"), "\n") {
		out.WriteString("    " + line + "\n")
	}
	return out.String()
}

