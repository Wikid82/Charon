const (
	pemCert      = "-----BEGIN CERTIFICATE-----\nMIIBszCCAVmgAwIBAgIUY2VydC1ib2R5\n-----END CERTIFICATE-----\n"
	pemPublicKey = "-----BEGIN PUBLIC KEY-----\nMFwwDQYJKoZIhvcNAQEBBQADSwAwSAJBAKj3\n-----END PUBLIC KEY-----\n"
)

// keyArmor returns a key-shaped block with the given label. The text is assembled so that no complete
// armor line appears in the source.
func keyArmor(label string) string {
	return "-----BEGIN " + label + "-----\nMIIBOgIBAAJBAKj34GkxFhD90vcNLYLInFEX6Ppy1tPf9Cnzj4p4WGeKLs1Pt8Qu\n-----END " + label + "-----\n"
}

var pemRSA = keyArmor("RSA PRIVATE KEY")

// exportedKeyTree exports a nested-layout tree holding the given config files and returns the entries.
func exportedKeyTree(t *testing.T, files map[string]string) map[string]string {
	t.Helper()
	dir := t.TempDir()
	tree := map[string]string{"config/config.yaml": "api:\n  server:\n    listen_uri: 0.0.0.0:8080\n"}
	for name, content := range files {
		tree[name] = content
	}
	writeExportTree(t, dir, tree)
	_, entries, _ := exportEntries(t, dir)
	return entries
}

func httpPlugin(extra string) string {
	return "type: http\nname: http_default\nurl: https://hooks.example.invalid/notify\nmethod: POST\n" + extra
}

func TestExportArchiveLeavesOutFilesNamedByKeyPath(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	absolute := filepath.Join(dir, "certs", "absolute.pem")
	writeExportTree(t, dir, map[string]string{
		"config/config.yaml": "api:\n  server:\n    listen_uri: 0.0.0.0:8080\n",
		"config/notifications/http_default.yaml": httpPlugin("cert_path: /etc/crowdsec/ssl/client.crt\n" +
			"key_path: /etc/crowdsec/ssl/client.pem\nca_cert_path: /etc/crowdsec/ssl/ca.crt\n"),
		"config/notifications/http_data.yaml": strings.Replace(httpPlugin("key_path: "+absolute+"\n"), "http_default", "http_data", 1),
		"config/ssl/client.crt":               "client certificate body\n",
		"config/ssl/ca.crt":                   "authority body\n",
		"config/ssl/client.pem":               "opaque private material\n",
		"certs/absolute.pem":                  "more opaque private material\n",
		"certs/unrelated.pem":                 "not referenced\n",
	})

	_, entries, _ := exportEntries(t, dir)

	require.NotContains(t, entries, "config/ssl/client.pem", "a key_path target stays on the host")
	require.NotContains(t, entries, "certs/absolute.pem", "a key_path below the data folder stays on the host")
	require.Contains(t, entries, "config/ssl/client.crt")
	require.Contains(t, entries, "config/ssl/ca.crt")
	require.Contains(t, entries, "certs/unrelated.pem")
	require.Contains(t, entries, "config/notifications/http_default.yaml")
	require.Contains(t, entries["config/notifications/http_default.yaml"], "key_path: /etc/crowdsec/ssl/client.pem")
}

