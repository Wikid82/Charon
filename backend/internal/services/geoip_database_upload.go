// MaxGeoIPDatabaseBytes is the largest database an upload may carry.
const MaxGeoIPDatabaseBytes = 32 << 20

// geoipFutureTolerance is how far ahead of the clock a build date may be. It allows for clock skew and no more: the
// resolver prefers the newest copy, so a future-dated file would win over every later bundled update.
const geoipFutureTolerance = 24 * time.Hour

const (
	// prevSuffix names the copy kept beside the data-folder copy while a change is in progress, so a failed change can
	// put it back.
	prevSuffix = ".prev"
	// uploadTempPrefix starts the temporary file an upload is streamed into. The name is generated by os.CreateTemp in
	// the data folder; nothing from the client contributes to it.
	uploadTempPrefix = "." + geoip.DatabaseFileName + ".upload-"
	// uploadTempPattern is the os.CreateTemp pattern for uploads.
	uploadTempPattern = uploadTempPrefix + "*"
)

// Sentinel errors of the upload, removal and rollback paths. Handlers map them to status codes and stable error codes;
// the wrapped detail is for the server log only. The geoip package's validation sentinels pass through unchanged.
var (
	// ErrGeoIPCustomPathSet is returned when CHARON_GEOIP_DB_PATH selects the database, so the data folder is not changed.
	ErrGeoIPCustomPathSet = errors.New("geoip database is set by CHARON_GEOIP_DB_PATH")
	// ErrGeoIPNoDataCopy is returned when removing the data-folder copy and there is none.
	ErrGeoIPNoDataCopy = errors.New("no data-folder geoip database to remove")
	// ErrGeoIPTooLarge is returned when an upload is over MaxGeoIPDatabaseBytes.
	ErrGeoIPTooLarge = errors.New("geoip database exceeds the upload limit")
	// ErrGeoIPUploadRead is returned when the upload could not be read for a reason other than its size.
	ErrGeoIPUploadRead = errors.New("geoip upload could not be read")
	// ErrGeoIPBuildDateInFuture is returned when the upload's build date is past the clock plus the tolerance.
	ErrGeoIPBuildDateInFuture = errors.New("geoip build date is in the future")
	// ErrGeoIPOlderThanCurrent is returned when the upload is older than the database in use or the bundled copy.
	ErrGeoIPOlderThanCurrent = errors.New("geoip database is older than the current database")
	// ErrGeoIPDataFolderReadOnly is returned when the data folder cannot be written.
	ErrGeoIPDataFolderReadOnly = errors.New("geoip data folder is read-only")
	// ErrGeoIPWriteFailed is returned when the data folder could not be changed for another reason.
	ErrGeoIPWriteFailed = errors.New("geoip database write failed")
)

// OlderThanCurrentError is ErrGeoIPOlderThanCurrent with the two build epochs, Unix seconds, for the response.
type OlderThanCurrentError struct {
	Uploaded uint
	Current  uint
}

// Error describes the refusal with both epochs.
func (e *OlderThanCurrentError) Error() string {
	return fmt.Sprintf("%s: uploaded %d, current %d", ErrGeoIPOlderThanCurrent, e.Uploaded, e.Current)
}

// Unwrap returns ErrGeoIPOlderThanCurrent so errors.Is matches the sentinel.
func (e *OlderThanCurrentError) Unwrap() error { return ErrGeoIPOlderThanCurrent }

// ReplaceResult describes an upload. It is returned with the error too, so the caller can audit a refused upload with
// its size and digest when they are known.
type ReplaceResult struct {
	// ReplacedPrevious reports whether a data-folder copy was replaced.
	ReplacedPrevious bool
	// Info is the metadata of the installed database; zero when the upload was refused before validation.
	Info geoip.DatabaseInfo
	// SizeBytes is the number of bytes read from the upload.
	SizeBytes int64
	// SHA256 is the hex digest of the upload; empty when it was not read in full.
	SHA256 string
}

// swapState records what a change replaced, so a failed step can put the previous state back.
type swapState struct {
	live, prev  string
	hadPrevious bool
	before      GeoIPInfo
}

// Replace installs an uploaded country database as the data-folder copy. The upload is streamed into a temporary file
// in the data folder, validated, and renamed into place; the copy it replaces is kept as .prev until the new database
// is loaded and the proxy config applied. Any failure after the rename restores the previous state.
func (s *GeoIPDatabaseStore) Replace(ctx context.Context, upload io.Reader) (ReplaceResult, error) {
	if !s.mu.TryLock() {
		return ReplaceResult{}, ErrGeoIPBusy
	}
	defer s.mu.Unlock()
	if s.envInEffect() {
		return ReplaceResult{}, ErrGeoIPCustomPathSet
	}

	live := s.dataPath
	dir := filepath.Dir(live)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return ReplaceResult{}, folderWriteError(err)
	}
	hadPrevious, err := regularTarget(live)
	if err != nil {
		return ReplaceResult{}, err
	}

	tmp, err := os.CreateTemp(dir, uploadTempPattern)
	if err != nil {
		return ReplaceResult{}, folderWriteError(err)
	}
	tmpPath := tmp.Name()
	// The temporary file is removed on every path; after a successful rename the name no longer exists.
	defer func() {
		_ = tmp.Close()
		_ = os.Remove(tmpPath)
	}()

	size, digest, err := s.copyUpload(tmp, upload)
	result := ReplaceResult{SizeBytes: size, SHA256: digest}
	if err != nil {
		return result, err
	}

	info, err := geoip.ValidateCountryDatabase(tmpPath)
	if err != nil {
		return result, err
	}
	result.Info = info
	if err := s.checkBuildEpoch(info.BuildEpoch); err != nil {
		return result, err
	}

	st := swapState{live: live, prev: live + prevSuffix, hadPrevious: hadPrevious, before: s.svc.Info()}
	if hadPrevious {
		if err := os.Rename(live, st.prev); err != nil {
			return result, folderWriteError(err)
		}
	}
	if err := os.Rename(tmpPath, live); err != nil {
		restoreFiles(st)
		return result, folderWriteError(err)
	}
	if err := syncDir(dir); err != nil {
		restoreFiles(st)
		return result, folderWriteError(err)
	}
	if err := s.loadFile(live); err != nil {
		s.restore(ctx, st)
		return result, fmt.Errorf("%w: %w", ErrGeoIPReloadFailed, err)
	}
	if err := s.applyIfSet(ctx); err != nil {
		s.restore(ctx, st)
		return result, fmt.Errorf("%w: %w", ErrGeoIPApplyFailed, err)
	}

	if hadPrevious {
		_ = os.Remove(st.prev) // a leftover .prev is removed by the next startup sweep
	}
	result.ReplacedPrevious = hadPrevious
	return result, nil
}

// copyUpload streams the upload into dst and returns its size and digest. The read is capped at maxBytes+1 bytes, so
// an over-size upload is detected without buffering it. A write failure is reported as a write failure, not as an
// unreadable upload.
func (s *GeoIPDatabaseStore) copyUpload(dst *os.File, upload io.Reader) (size int64, digest string, err error) {
	hasher := sha256.New()
	w := &uploadWriter{dst: io.MultiWriter(dst, hasher)}
	n, err := io.Copy(w, io.LimitReader(upload, s.maxBytes+1))
	switch {
	case n > s.maxBytes:
		return n, "", ErrGeoIPTooLarge
	case w.err != nil:
		return n, "", folderWriteError(w.err)
	case err != nil:
		return n, "", ClassifyUploadRead(err)
	}
	if err := dst.Sync(); err != nil {
		return n, "", folderWriteError(err)
	}
	if err := dst.Close(); err != nil {
		return n, "", folderWriteError(err)
	}
	return n, hex.EncodeToString(hasher.Sum(nil)), nil
}

// ClassifyUploadRead marks a failure while reading an upload as ErrGeoIPUploadRead. An error that already carries that
// sentinel is returned as it is, and so is an oversized body, which keeps its *http.MaxBytesError type so the API maps
// it to 413.
func ClassifyUploadRead(err error) error {
	var maxErr *http.MaxBytesError
	if errors.As(err, &maxErr) || errors.Is(err, ErrGeoIPUploadRead) {
		return err
	}
	return fmt.Errorf("%w: %w", ErrGeoIPUploadRead, err)
}

// uploadWriter remembers the first write error, so a failed write can be told apart from a failed read.
type uploadWriter struct {
	dst io.Writer
	err error
}

// Write forwards p to the destination and records the first failure.
func (w *uploadWriter) Write(p []byte) (int, error) {
	n, err := w.dst.Write(p)
	if err != nil && w.err == nil {
		w.err = err
	}
	return n, err
}

// checkBuildEpoch refuses a build date in the future, and one older than the database in use or the bundled copy,
// whichever is newer. Equal dates are accepted.
func (s *GeoIPDatabaseStore) checkBuildEpoch(epoch uint) error {
	if time.Unix(int64(epoch), 0).After(s.now().Add(geoipFutureTolerance)) {
		return ErrGeoIPBuildDateInFuture
	}
	var current uint
	if info := s.svc.Info(); info.Loaded {
		current = info.BuildEpoch
	}
	if bundled, ok := s.includedBuildEpoch(); ok && bundled > current {
		current = bundled
	}
	if epoch < current {
		return &OlderThanCurrentError{Uploaded: epoch, Current: current}
	}
	return nil
}

// DataCopyInfo returns the metadata of the data-folder copy. It is the zero value when there is no copy or it cannot be
// read; the caller reads it before a removal so the audit entry can name the removed build.
func (s *GeoIPDatabaseStore) DataCopyInfo() geoip.DatabaseInfo {
	if !isRegularFile(s.dataPath) {
		return geoip.DatabaseInfo{}
	}
	info, err := geoip.Inspect(s.dataPath)
	if err != nil {
		return geoip.DatabaseInfo{}
	}
	return info
}

// RemoveDataCopy deletes the data-folder copy and loads the bundled copy in its place, or unloads the database when the
// image ships none. The proxy config is applied afterwards. A failure restores the removed copy.
func (s *GeoIPDatabaseStore) RemoveDataCopy(ctx context.Context) error {
	if !s.mu.TryLock() {
		return ErrGeoIPBusy
	}
	defer s.mu.Unlock()
	if s.envInEffect() {
		return ErrGeoIPCustomPathSet
	}

	live := s.dataPath
	exists, err := regularTarget(live)
	if err != nil {
		return err
	}
	if !exists {
		return ErrGeoIPNoDataCopy
	}

	st := swapState{live: live, prev: live + prevSuffix, hadPrevious: true, before: s.svc.Info()}
	if err := os.Rename(live, st.prev); err != nil {
		return folderWriteError(err)
	}
	if err := syncDir(filepath.Dir(live)); err != nil {
		restoreFiles(st)
		return folderWriteError(err)
	}
	if err := s.loadBundledOrUnload(); err != nil {
		s.restore(ctx, st)
		return fmt.Errorf("%w: %w", ErrGeoIPReloadFailed, err)
	}
	if err := s.applyIfSet(ctx); err != nil {
		s.restore(ctx, st)
		return fmt.Errorf("%w: %w", ErrGeoIPApplyFailed, err)
	}

	_ = os.Remove(st.prev) // a leftover .prev is removed by the next startup sweep
	return nil
}

// loadBundledOrUnload loads the bundled copy by its explicit path, so the result does not depend on the path resolver.
// When the image ships no copy, the service is closed and no database is in use.
func (s *GeoIPDatabaseStore) loadBundledOrUnload() error {
	if !isRegularFile(s.bundledPath) {
		_ = s.svc.Close()
		return nil
	}
	return s.loadFile(s.bundledPath)
}

// applyIfSet applies the proxy config when a proxy is wired to the store.
func (s *GeoIPDatabaseStore) applyIfSet(ctx context.Context) error {
	if s.apply == nil {
		return nil
	}
	return s.apply(ctx)
}

// restore puts the previous files and database back after a failed change, then applies the proxy config again on a
// best-effort basis. Each step ignores its own error: the caller already reports the original failure.
func (s *GeoIPDatabaseStore) restore(ctx context.Context, st swapState) {
	restoreFiles(st)
	if st.before.Loaded {
		_ = s.svc.LoadFrom(st.before.Path)
	} else {
		_ = s.svc.Close()
	}
	_ = s.applyIfSet(ctx)
}

// restoreFiles moves the previous copy back to the live path, or removes the new file when there was no previous copy.
func restoreFiles(st swapState) {
	if st.hadPrevious {
		_ = os.Rename(st.prev, st.live)
		return
	}
	_ = os.Remove(st.live)
}

// regularTarget reports whether path names an existing regular file. A missing path is not an error. A symlink or any
// other non-regular entry is refused, so a write never follows a link out of the data folder.
func regularTarget(path string) (bool, error) {
	info, err := os.Lstat(path)
	switch {
	case errors.Is(err, fs.ErrNotExist):
		return false, nil
	case err != nil:
		return false, folderWriteError(err)
	case !info.Mode().IsRegular():
		return false, fmt.Errorf("%w: target is not a regular file", ErrGeoIPWriteFailed)
	}
	return true, nil
}

// folderWriteError classifies a failed change to the data folder. A read-only folder gets its own sentinel so the API
// can say so; the OS text is kept for the server log only.
func folderWriteError(err error) error {
	if errors.Is(err, fs.ErrPermission) || errors.Is(err, unix.EROFS) {
		return fmt.Errorf("%w: %w", ErrGeoIPDataFolderReadOnly, err)
	}
	return fmt.Errorf("%w: %w", ErrGeoIPWriteFailed, err)
}

// syncDir flushes the directory entry of a rename to disk.
func syncDir(dir string) error {
	d, err := os.Open(filepath.Clean(dir))
	if err != nil {
		return err
	}
	defer func() { _ = d.Close() }()
	return d.Sync()
}

// SweepGeoIPDataFolder clears what an interrupted upload or removal left in the data folder of livePath. Upload temp
// files are deleted. A .prev copy is moved back when the live copy is missing, and deleted when both exist: the rename
// that installs an upload is atomic, so the live copy is then complete. It runs once at startup, before the database is
// resolved.
func SweepGeoIPDataFolder(livePath string) error {
	dir := filepath.Dir(livePath)
	entries, err := os.ReadDir(dir)
	if errors.Is(err, fs.ErrNotExist) {
		return nil
	}
	if err != nil {
		return fmt.Errorf("read geoip data folder: %w", err)
	}

	var errs []error
	for _, entry := range entries {
		if !strings.HasPrefix(entry.Name(), uploadTempPrefix) {
			continue
		}
		if err := os.Remove(filepath.Join(dir, entry.Name())); err != nil {
			errs = append(errs, fmt.Errorf("remove interrupted geoip upload: %w", err))
		}
	}

	prev := livePath + prevSuffix
	liveExists := isRegularFile(livePath)
	switch {
	case isRegularFile(prev) && !liveExists:
		if err := os.Rename(prev, livePath); err != nil {
			errs = append(errs, fmt.Errorf("restore previous geoip database: %w", err))
		}
	case isRegularFile(prev):
		if err := os.Remove(prev); err != nil {
			errs = append(errs, fmt.Errorf("remove previous geoip database: %w", err))
		}
	}
	return errors.Join(errs...)
}
